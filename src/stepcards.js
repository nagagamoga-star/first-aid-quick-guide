/* Per-step photographs.
   STEP_CARDS is generated by src/build.py from data/step-cards.json.
   A picture is chosen by topic id and step index (the same id Illustrate uses,
   "<topic>:<index>"). Add a row to tools/build_topic_cards.py to cover another
   step. A step with no row keeps its drawing, or its accepted diagram.
   These pictures are not clinically reviewed. The alt text is the step text. */
var StepCards = (function(){
  var items = (typeof STEP_CARDS !== 'undefined' && STEP_CARDS.items) || [];
  var bySlot = {}, byId = {};
  items.forEach(function(it){
    bySlot[it.topic + ':' + it.step] = it;
    byId[it.id] = it;
  });
  function esc(s){ return String(s == null ? '' : s).replace(/[&<>"]/g, function(c){ return { '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;' }[c]; }); }
  function reviewNote(){
    var r = (typeof REVIEWS !== 'undefined' && REVIEWS.illustrations) || null;
    if (!r || r.status === 'APPROVED FOR PUBLICATION') return '';
    return '<span class="dg-review">Picture not yet clinically reviewed.</span>';
  }

  Illustrate.use(function(s){
    if (s.step === 'icon') return '';
    var it = bySlot[s.id];
    if (!it) return '';
    var fallback = (typeof ART !== 'undefined' && ART.svg) ? ART.svg(s.spec) : '';
    return '<figure class="dg step-photo">' +
      '<button type="button" class="dg-zoom" data-stepcard="' + esc(it.id) + '" aria-label="Enlarge picture: ' + esc(it.alt) + '">' +
        '<img src="' + esc(it.file) + '" alt="' + esc(it.alt) + '" width="' + esc(it.width) + '" height="' + esc(it.height) + '" loading="lazy" decoding="async"' +
        ' onerror="this.closest(\'figure\').classList.add(\'dg-off\')">' +
      '</button>' +
      '<div class="dg-fallback" aria-hidden="true">' + fallback + '</div>' +
      '<figcaption>' + reviewNote() + '</figcaption>' +
    '</figure>';
  });

  var dlg = null, opener = null;
  function open(it, from){
    if (!dlg){
      dlg = document.createElement('dialog');
      dlg.className = 'dg-dialog';
      dlg.setAttribute('aria-labelledby', 'stepCardCap');
      dlg.innerHTML = '<div class="dg-dlg-bar"><p id="stepCardCap"></p><button type="button" class="dg-close">Close</button></div>' +
        '<div class="dg-dlg-img"><img alt=""></div><p class="dg-dlg-credit"></p>';
      document.body.appendChild(dlg);
      dlg.querySelector('.dg-close').addEventListener('click', function(){ dlg.close(); });
      dlg.addEventListener('click', function(e){ if (e.target === dlg) dlg.close(); });
      dlg.addEventListener('close', function(){ if (opener) opener.focus(); });
    }
    opener = from;
    dlg.querySelector('#stepCardCap').textContent = 'Picture not yet clinically reviewed.';
    var img = dlg.querySelector('img'); img.src = it.file; img.alt = it.alt;
    dlg.querySelector('.dg-dlg-credit').textContent = it.alt;
    if (dlg.showModal) dlg.showModal(); else dlg.setAttribute('open', '');
    dlg.querySelector('.dg-close').focus();
  }
  document.addEventListener('click', function(e){
    var b = e.target.closest && e.target.closest('.dg-zoom');
    if (!b) return;
    var it = byId[b.getAttribute('data-stepcard')];
    if (it) open(it, b);
  });

  return { items: items };
})();
