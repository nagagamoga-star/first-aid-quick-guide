/* Diagrams from Wikimedia Commons, stored in assets/diagrams/.
   MEDIA is generated by src/build.py from data/media.json and holds only the
   diagrams a person has accepted and whose licence the Commons API confirmed.
   This adds an Illustrate renderer: a step whose drawing key has an accepted
   diagram shows the diagram; every other step keeps its drawing from art.js.
   Topic symbols on the home screen stay drawings (step "icon" is skipped).

   Each diagram sits on a light panel in both themes (Commons diagrams are drawn
   for white paper), opens full screen when tapped, and falls back to the
   drawing if the file can't load (for example offline before it was saved). */
var Media = (function(){
  var all = (typeof MEDIA !== 'undefined' && MEDIA.items) || [];
  var items = all.filter(function(it){ return it.decision === 'accepted'; });
  var hidden = {}, hiddenSlot = {};
  all.forEach(function(it){ if (it.decision === 'hidden'){ (it.keys || []).forEach(function(k){ hidden[k] = 1; }); (it.slots || []).forEach(function(s){ hiddenSlot[s] = 1; }); } });
  var byKey = {}, bySlot = {}, byId = {};
  items.forEach(function(it){
    byId[it.id] = it;
    (it.keys || []).forEach(function(k){ byKey[k] = it; });
    (it.slots || []).forEach(function(s){ bySlot[s] = it; });
  });
  function esc(s){ return String(s == null ? '' : s).replace(/[&<>"]/g, function(c){ return { '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;' }[c]; }); }
  function link(href, text){ return href ? '<a href="' + esc(href) + '">' + esc(text) + '</a>' : esc(text); }
  function gen(it){ return it.origin === 'generated'; }
  function shortCredit(it){ return gen(it) ? 'AI-generated picture' : esc(it.author || 'Unknown author') + ', ' + esc(it.licence); }
  function fullCredit(it){
    if (gen(it)) return esc(it.caption) + ': AI-generated picture supplied by the site owner.';
    return link(it.sourceUrl, it.commons.replace(/^File:/, '')) + ' by ' + esc(it.author || 'unknown author') +
      ', ' + link(it.licenceUrl, it.licence) + ', via Wikimedia Commons.' + (it.credit && /Resized/.test(it.credit) ? ' Resized and converted to WebP.' : '');
  }

  /* Pictures share the 'illustrations' review item. Until it is approved, each
     diagram says so; an owner override says who published it before review. */
  function reviewNote(){
    var r = (typeof REVIEWS !== 'undefined' && REVIEWS.illustrations) || null;
    if (!r || r.status === 'APPROVED FOR PUBLICATION') return '';
    return '<span class="dg-review">' + (r.override ? 'Picture published by the site owner before clinical review.' : 'Picture not yet clinically reviewed.') + '</span>';
  }

  Illustrate.use(function(s){
    if (s.step === 'icon') return '';
    // A drawing judged unclear with no suitable replacement: show no picture.
    if (hiddenSlot[s.id] || hidden[s.key]) return '<span class="pic-hidden" hidden></span>';
    var it = bySlot[s.id] || byKey[s.key];
    if (!it) return '';
    var fallback = (typeof ART !== 'undefined' && ART.svg) ? ART.svg(s.spec) : '';
    return '<figure class="dg">' +
      '<button type="button" class="dg-zoom" data-media="' + esc(it.id) + '" aria-label="Enlarge picture: ' + esc(it.caption) + '">' +
        '<img src="' + esc(it.file) + '" alt="' + esc(it.alt) + '" width="' + (it.width || '') + '" height="' + (it.height || '') + '" loading="lazy" decoding="async"' +
        ' onerror="this.closest(\'figure\').classList.add(\'dg-off\')">' +
      '</button>' +
      '<div class="dg-fallback" aria-hidden="true">' + fallback + '</div>' +
      '<figcaption>' + esc(it.caption) + ' <span class="dg-credit">' + shortCredit(it) + '</span>' + reviewNote() + '</figcaption>' +
    '</figure>';
  });

  /* Full-screen view. Native <dialog>: Esc closes it, focus returns to the
     picture, and pinch zoom works inside it on phones. */
  var dlg = null, opener = null;
  function open(it, from){
    if (!dlg){
      dlg = document.createElement('dialog');
      dlg.className = 'dg-dialog';
      dlg.setAttribute('aria-labelledby', 'dgCap');
      dlg.innerHTML = '<div class="dg-dlg-bar"><p id="dgCap"></p><button type="button" class="dg-close">Close</button></div>' +
        '<div class="dg-dlg-img"><img alt=""></div><p class="dg-dlg-credit"></p>';
      document.body.appendChild(dlg);
      dlg.querySelector('.dg-close').addEventListener('click', function(){ dlg.close(); });
      dlg.addEventListener('click', function(e){ if (e.target === dlg) dlg.close(); });
      dlg.addEventListener('close', function(){ if (opener) opener.focus(); });
    }
    opener = from;
    dlg.querySelector('#dgCap').textContent = it.caption;
    var img = dlg.querySelector('img'); img.src = it.file; img.alt = it.alt;
    dlg.querySelector('.dg-dlg-credit').innerHTML = fullCredit(it);
    if (dlg.showModal) dlg.showModal(); else dlg.setAttribute('open', '');
    dlg.querySelector('.dg-close').focus();
  }
  document.addEventListener('click', function(e){
    var b = e.target.closest && e.target.closest('.dg-zoom');
    if (b && byId[b.getAttribute('data-media')]) open(byId[b.getAttribute('data-media')], b);
  });

  /* Credits: one line per diagram in use, beside the BodyParts3D credit. */
  function credits(){
    var host = document.querySelector('footer .licences');
    if (!host || !items.length || document.getElementById('dgCredits')) return;
    var sec = document.createElement('div');
    sec.id = 'dgCredits';
    var commons = items.filter(function(it){ return !gen(it); }), made = items.filter(gen);
    sec.innerHTML = '<h3>Pictures</h3>' +
      (made.length ? '<p>' + made.length + ' step pictures are AI-generated images supplied by the site owner. A generated picture is not evidence of correct technique; the step text is the instruction. None has been clinically reviewed yet.</p>' : '') +
      (commons.length ? '<p>These diagrams are from Wikimedia Commons, used under the licence shown, and stored with this guide so they work offline.</p><ul>' +
        commons.map(function(it){ return '<li>' + fullCredit(it) + '</li>'; }).join('') + '</ul>' : '') +
      '<p>Where no picture fits Australian guidance, the guide keeps its own drawing or shows text only.</p>';
    host.appendChild(sec);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', credits); else credits();

  return { items: items };
})();
